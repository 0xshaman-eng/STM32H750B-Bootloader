/**
  * @brief This function handles USART3 global interrupt.
  */
void USART3_IRQHandler(void)
{
  /* USER CODE BEGIN USART3_IRQn 0 */
  /* Lean RXNE handler: we manage UART RX directly (not via HAL's
   * interrupt-mode receive), pushing each byte into the transport ring
   * buffer. We deliberately do NOT call HAL_UART_IRQHandler here. */

  /* Byte received? (RXNE = Read Data Register Not Empty) */
  if (__HAL_UART_GET_FLAG(&huart3, UART_FLAG_RXNE) != RESET)
  {
      /* Reading RDR clears the RXNE flag automatically */
      uint8_t byte = (uint8_t)(huart3.Instance->RDR & 0xFF);
      UART_Transport_RxByte(byte);
  }

  /* Overrun happened? Clear it so the peripheral keeps receiving.
   * (A dropped byte here is far better than a wedged UART -- the
   * protocol's CRC + retry will recover the packet.) */
  if (__HAL_UART_GET_FLAG(&huart3, UART_FLAG_ORE) != RESET)
  {
      __HAL_UART_CLEAR_OREFLAG(&huart3);
  }

  return;
  /* USER CODE END USART3_IRQn 0 */
  HAL_UART_IRQHandler(&huart3);
  /* USER CODE BEGIN USART3_IRQn 1 */

  /* USER CODE END USART3_IRQn 1 */
}

